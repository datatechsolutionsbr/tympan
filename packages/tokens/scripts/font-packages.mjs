// Writes the bundled-font output of one package (fonts/manifest.json and
// THIRD_PARTY_NOTICES.md) from the full manifest built by fetch-fonts.mjs.
// The font files themselves are already in <package>/fonts/<slug>/.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packagesDir = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

export const PACKAGES = {
  tokens: {
    dir: join(packagesDir, 'tokens'),
    name: '@datatechsolutions/tympan-tokens',
    licence: 'is licensed under FSL-1.1-ALv2 (Copyright 2026 Natalia Mesquita).',
    scope: 'every family the Tympan themes name except the CJK Noto families (those are in @datatechsolutions/tympan-fonts-cjk)',
  },
  'fonts-cjk': {
    dir: join(packagesDir, 'fonts-cjk'),
    name: '@datatechsolutions/tympan-fonts-cjk',
    licence: 'contains only the font files below (and generated @font-face rules); the files are under their own licence.',
    scope: 'the CJK Noto families named by the Tympan token stacks (Japanese, Simplified and Traditional Chinese, Korean)',
  },
}

/**
 * `manifest` is { fetched, families, faces, specs } over every family;
 * `keep(family)` selects this package's share. Returns totals.
 */
export function writeFontPackage(name, manifest, keep) {
  const p = PACKAGES[name]
  const families = Object.fromEntries(Object.entries(manifest.families).filter(([f]) => keep(f)).sort(([a], [b]) => a.localeCompare(b)))
  const faces = Object.fromEntries(Object.entries(manifest.faces).filter(([, f]) => keep(f.family)))
  const specs = Object.fromEntries(Object.entries(manifest.specs).filter(([s]) => keep(s.split(':')[0])))
  const out = {
    $comment: 'Generated by packages/tokens/scripts/fetch-fonts.mjs. Do not edit; rerun the script.',
    fetched: manifest.fetched,
    origin: 'Google Fonts css2 API (fonts.googleapis.com, woff2 sliced by unicode-range), files from fonts.gstatic.com; licences from github.com/google/fonts',
    families,
    faces,
    specs,
  }
  writeFileSync(join(p.dir, 'fonts', 'manifest.json'), JSON.stringify(out, null, 1) + '\n')
  const mb = (n) => `${(n / 1048576).toFixed(2)} MB`
  const rows = Object.entries(families).map(([family, f]) => `| ${family} | ${f.version ?? ''} | ${f.license} | ${f.designer ?? ''} | ${f.files} | ${mb(f.bytes)} | \`fonts/${f.licenseFile}\` |`)
  const files = Object.keys(faces).length
  const bytes = Object.values(faces).reduce((n, f) => n + f.bytes, 0)
  writeFileSync(
    join(p.dir, 'THIRD_PARTY_NOTICES.md'),
    [
      '# Third-party notices',
      '',
      `\`${p.name}\` ${p.licence}`,
      `It bundles the font files below, unmodified, in \`fonts/\`: ${p.scope}`,
      `(generated by \`packages/tokens/scripts/fetch-fonts.mjs\`; fetched ${manifest.fetched} from the Google Fonts css2 API`,
      'as woff2 sliced by unicode-range). Each family keeps its own licence, shipped next to its files.',
      'The SIL Open Font License 1.1 allows bundling and redistribution with software; the fonts may',
      'not be sold by themselves, and Reserved Font Names apply to modified versions (none here are modified).',
      'Font-file sizes: see `fonts/manifest.json`.',
      '',
      '| Family | Version (gstatic) | Licence | Designer | Files | Size | Licence file |',
      '|---|---|---|---|---|---|---|',
      ...rows,
      '',
      `Total: ${Object.keys(families).length} families, ${files} files, ${mb(bytes)}.`,
      '',
    ].join('\n'),
  )
  return { families: Object.keys(families).length, files, bytes }
}
